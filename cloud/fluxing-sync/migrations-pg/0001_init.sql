-- ---------------------------------------------------------------------------
-- 执行前置（四条，缺一不可）
-- ---------------------------------------------------------------------------
-- 1. 确认 PG 大版本：SELECT version();
--    最低 10（GENERATED ... AS IDENTITY 需 10+），本批按 ≥14 设计。
--    未回读前不得假定版本（handoff §Q-10.6 未证实项 U-1）。
--
-- 2. 建库必须指定 LC_COLLATE 'C'（等价于 SQLite 的 BINARY 比较）：
--
--      CREATE DATABASE fluxing_sync
--        WITH TEMPLATE = template0
--             ENCODING = 'UTF8'
--             LC_COLLATE = 'C'
--             LC_CTYPE  = 'C';
--
--    理由见附录 B-6：若库建成 en_US.UTF-8 等 libc 排序，UNIQUE(email) /
--    UNIQUE(user_id, item_key) 可能把字节不同的两个串判成相等。
--    这一条漏了不是「慢一点」，是**唯一性判据被换掉**。
--
-- 3. 应用连库走独立角色 + 密码进 .env，不进仓库、不进日志、不拼命令行：
--      CREATE ROLE fluxing_sync LOGIN PASSWORD '<见 .env>';
--      GRANT CONNECT ON DATABASE fluxing_sync TO fluxing_sync;
--      GRANT USAGE ON SCHEMA public TO fluxing_sync;
--      GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO fluxing_sync;
--      GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO fluxing_sync;
--    （不需要 DDL 权限给应用角色；迁移用管理员角色执行。）
--
-- 4. 执行后回读，两个数字必须相等，否则本文件没跑全：
--      SELECT count(*) FROM information_schema.tables
--       WHERE table_schema='public' AND table_type='BASE TABLE';   -- 期望 9
--      SELECT count(*) FROM pg_indexes WHERE schemaname='public';  -- 期望 22
--    （9 = 8 张业务表 + 1 张 schema_migrations 账本；与 D1 生产 num_tables=9
--      ——8 表 + d1_migrations——逐一对位，见 §Q-10.3。）
--
-- 整个文件在一个事务里执行（PG 的 DDL 是事务性的）：
--   psql -v ON_ERROR_STOP=1 -1 -f migrations-pg/0001_init.sql
-- 失败则整体回滚，不留半套结构。**不使用** IF NOT EXISTS 掩盖重跑，
-- 重跑一律先 DROP DATABASE（迁移期还没有需要保留的数据）。
-- ---------------------------------------------------------------------------

BEGIN;

-- ---------------------------------------------------------------- users
-- 差异：kdf_iters / created_at 由 SQLite INTEGER(64 位) → PG BIGINT。
--       PG 的 INTEGER 只有 32 位，epoch ms ≈ 1.79e12 直接溢出（附录 B-1）。
-- 差异：email_verified 由 INTEGER NOT NULL DEFAULT 0 → SMALLINT 同默认值。
--       **不用 BOOLEAN**：布尔位一旦变 boolean，驱动返回 true/false，
--       /account/me 一类响应的 JSON 形状就变了（附录 B-3）。
CREATE TABLE users (
  id             TEXT PRIMARY KEY,
  email          TEXT NOT NULL UNIQUE,
  -- verifier = base64(HMAC-SHA256(AUTH_PEPPER, auth_key))，见 plan §3.2
  verifier       TEXT NOT NULL,
  -- salt = base64(16 字节随机)，客户端用它跑 PBKDF2；服务端不复用
  salt           TEXT NOT NULL,
  kdf_algo       TEXT NOT NULL,
  kdf_iters      BIGINT NOT NULL,
  email_verified SMALLINT NOT NULL DEFAULT 0,
  created_at     BIGINT NOT NULL
);

-- ---------------------------------------------------------------- devices
CREATE TABLE devices (
  id         TEXT PRIMARY KEY,
  user_id    TEXT NOT NULL REFERENCES users(id),
  name       TEXT NOT NULL,
  device_id  TEXT NOT NULL,
  last_seen  BIGINT NOT NULL,
  revoked_at BIGINT,
  created_at BIGINT NOT NULL
);
CREATE UNIQUE INDEX idx_devices_user_device ON devices(user_id, device_id);

-- ---------------------------------------------------------- refresh_tokens
-- 注意：device_id 指向 devices.id（行主键），不是客户端上报的 device_id。
--       D1 原文**没有**给这一列建 FK，PG 侧同样不建——令牌的生命周期比设备行长
--       （撤销设备后旧令牌仍需按哈希查出来判 401），加 FK 会让「删设备」失败。
CREATE TABLE refresh_tokens (
  id         TEXT PRIMARY KEY,
  user_id    TEXT NOT NULL REFERENCES users(id),
  device_id  TEXT NOT NULL,
  kind       TEXT NOT NULL,
  token_hash TEXT NOT NULL UNIQUE,
  expires_at BIGINT NOT NULL,
  revoked_at BIGINT,
  created_at BIGINT NOT NULL
);
CREATE UNIQUE INDEX idx_tokens_hash ON refresh_tokens(token_hash);
CREATE INDEX idx_tokens_user ON refresh_tokens(user_id);

-- -------------------------------------------------------------- sync_items
-- 差异：id 由 INTEGER PRIMARY KEY AUTOINCREMENT →
--       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY。
--       · AUTOINCREMENT 的语义是「删行后不复用 rowid」，IDENTITY 的序列同样不回收，
--         二者等价；客户端的 since 增量拉游标因此不会回退（附录 B-4）。
--       · 必须是 BY DEFAULT 而非 ALWAYS：从 D1 导数据时要**保号直插** id，
--         否则所有客户端手里的 since 游标全部错位。导入后必须 setval（附录 B-4）。
CREATE TABLE sync_items (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     TEXT NOT NULL REFERENCES users(id),
  item_key    TEXT NOT NULL,
  type        TEXT NOT NULL,
  hlc_ms      BIGINT NOT NULL,
  hlc_counter BIGINT NOT NULL,
  hlc_device  TEXT NOT NULL,
  r2_key      TEXT NOT NULL,
  nonce_b64   TEXT NOT NULL,
  cipher_len  BIGINT NOT NULL,
  updated_at  BIGINT NOT NULL
);
-- 每用户每 item_key 只留一行最新版本
CREATE UNIQUE INDEX idx_sync_user_item ON sync_items(user_id, item_key);
-- 增量拉：WHERE user_id = $1 AND id > $2 ORDER BY id
CREATE INDEX idx_sync_user_id ON sync_items(user_id, id);
-- 写预算护栏：WHERE user_id = $1 AND updated_at >= $2（原 0003）
CREATE INDEX idx_sync_user_updated ON sync_items(user_id, updated_at);

-- ----------------------------------------------------- email_verifications
CREATE TABLE email_verifications (
  id          TEXT PRIMARY KEY,
  email       TEXT NOT NULL,
  -- base64(HMAC-SHA256(AUTH_PEPPER, "email|code|created_at"))：
  -- 6 位码裸哈希可被 10^6 穷举，必须加 pepper
  code_hash   TEXT NOT NULL,
  attempts    BIGINT NOT NULL DEFAULT 0,
  expires_at  BIGINT NOT NULL,
  consumed_at BIGINT,
  created_at  BIGINT NOT NULL
);
CREATE INDEX idx_email_verify ON email_verifications(email, created_at);

-- ------------------------------------------------------------ mail_outbox
-- 仅供 MAIL_MODE="outbox"（本地 / 测试）使用；生产走 EMAIL 绑定，不写本表。
CREATE TABLE mail_outbox (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  to_addr    TEXT NOT NULL,
  subject    TEXT NOT NULL,
  body       TEXT NOT NULL,
  created_at BIGINT NOT NULL
);

-- --------------------------------------------------------- password_resets
-- 独立表而非给 email_verifications 加 purpose 列（原 0002 的取舍，理由见原文）。
CREATE TABLE password_resets (
  id          TEXT PRIMARY KEY,
  email       TEXT NOT NULL,
  -- base64(HMAC-SHA256(AUTH_PEPPER, "password-reset-v1|email|code|created_at"))
  code_hash   TEXT NOT NULL,
  attempts    BIGINT NOT NULL DEFAULT 0,
  expires_at  BIGINT NOT NULL,
  consumed_at BIGINT,
  created_at  BIGINT NOT NULL
);
-- 取最新一条重置码：WHERE email = $1 ORDER BY created_at DESC LIMIT 1
CREATE INDEX idx_password_resets_email ON password_resets(email, created_at);

-- ------------------------------------------------------------ sync_buckets
-- 路线 B 下本表**长期冻结**：桶化端点保留可服务、客户端停在 phase 0，
-- 阶段 3/4 永不启用（handoff §Q-9 / §Q-10）。保留 DDL 只为「旧客户端仍能打桶端点
-- 并拿到空结果」与「13 个既有测试仍可编译」。**不新增任何写入。**
-- 与 sync_items 的差异（原 0004 的 B1–B6，逐条保留）：
--   · device_id 存 devices.id（行主键），不是客户端上报的 device_id；
--   · 无 nonce_b64（ADR 0077 D3 不做桶级二次加密）；
--   · item_count = 桶内条目数，服务端不解析 blob；
--   · cipher_len 语义 = 桶 blob 字节数；
--   · id 是桶侧独立编号空间，与 sync_items.id 互不相干。
CREATE TABLE sync_buckets (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     TEXT NOT NULL REFERENCES users(id),
  device_id   TEXT NOT NULL,
  bucket_key  TEXT NOT NULL,
  hlc_ms      BIGINT NOT NULL,
  hlc_counter BIGINT NOT NULL,
  hlc_device  TEXT NOT NULL,
  r2_key      TEXT NOT NULL,
  cipher_len  BIGINT NOT NULL,
  item_count  BIGINT NOT NULL,
  updated_at  BIGINT NOT NULL
);
CREATE UNIQUE INDEX idx_sync_buckets_user_device_item
  ON sync_buckets(user_id, device_id, bucket_key);
CREATE INDEX idx_sync_buckets_user_id ON sync_buckets(user_id, id);
CREATE INDEX idx_sync_buckets_user_updated ON sync_buckets(user_id, updated_at);

-- ------------------------------------------------------- schema_migrations
-- 唯一**新增**的表（D1 时代由平台表 d1_migrations 承担，PG 侧没有等价物）。
-- 作用有二：① 记录四份 D1 迁移的来历，便于对账；② 0002+ 的 PG 迁移有落点。
CREATE TABLE schema_migrations (
  version    TEXT PRIMARY KEY,
  applied_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM now()) * 1000)::BIGINT
);

INSERT INTO schema_migrations (version) VALUES
  ('0001_init'),
  ('0002_password_resets'),
  ('0003_sync_items_updated_index'),
  ('0004_sync_buckets');

COMMIT;


-- ============================================================================
-- 附录 A · 列类型映射表（逐条）
-- ============================================================================
-- | SQLite（D1）                          | PostgreSQL                        | 说明 |
-- |---------------------------------------|-----------------------------------|------|
-- | TEXT PRIMARY KEY                      | TEXT PRIMARY KEY                  | 值来自应用（随机 hex/uuid），非自增，无差异 |
-- | INTEGER PRIMARY KEY AUTOINCREMENT      | BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY | 不复用 + 支持保号直插（B-4） |
-- | INTEGER（epoch ms / 秒）               | BIGINT                            | SQLite INTEGER 恒 64 位，PG INTEGER 32 位（B-1） |
-- | INTEGER（字节长度 / 计数）             | BIGINT                            | 同上，统一口径，避免逐列判断 |
-- | INTEGER NOT NULL DEFAULT 0（0/1 位）   | SMALLINT NOT NULL DEFAULT 0       | 保 JSON 形状（B-3） |
-- | TEXT（业务值）                         | TEXT                              | 未加长度限制；D1 也没有长度约束 |
-- | REFERENCES users(id)（内联）           | 同左（PG 强制生效）               | 删除顺序须由测试固定（B-5） |
--
-- 表数：8 业务表 + 1 账本 = 9；索引：9 PK + 11 显式 + 2 列级 UNIQUE = 22。
--
-- ============================================================================
-- 附录 B · PG 侧陷阱（每一条都能让移植「跑起来但错」）
-- ============================================================================
-- B-1  INTEGER 不是同一个 INTEGER。SQLite 的 INTEGER 一律 64 位，PG 的 INTEGER
--      是 32 位。created_at / updated_at / expires_at / hlc_ms 都是 epoch ms
--      （≈1.79e12），映射成 PG INTEGER 会让**每一次插入都直接报越界**。
--      → 本文件所有这类列一律 BIGINT。
--
-- B-2  int8 默认以字符串回到 JS。node-postgres 与 postgres.js 都把 BIGINT
--      (oid=20) 解析成 string，COUNT(*) 同样是 int8。若不处理，pull 响应里的
--      `id` 会从 123 变成 "123"、写预算护栏读到的 count 变成字符串 ——
--      **wire 契约静默变了，客户端 compareHlc / 游标比较会出错**。
--      → 驱动初始化必须显式设 int8 解析器（pg: types.setTypeParser(20, Number)；
--        postgres.js: types.bigint 解析器）。本批数据量下所有 int8 值 < 2^53，
--        用 Number 安全。这一条写进 recon §4 R6 与 node-server 的初始化代码。
--
-- B-3  0/1 位不要用 BOOLEAN。email_verified 在 D1 是整数 0/1，SQL 里按
--      `email_verified = 0` 比较、JSON 里是数字。改 boolean 会同时改掉
--      SQL 字面量与响应形状两处，且是**静默**的（true 在 JSON 里合法）。
--      → 用 SMALLINT。
--
-- B-4  IDENTITY 必须 BY DEFAULT，且导入后 setval。D1 的历史行要保号搬过来
--      （客户端手里的 since 游标就是 id）：BY ALWAYS 会拒绝显式 id。
--      导入后执行：
--        SELECT setval(pg_get_serial_sequence('sync_items','id'),
--                      (SELECT max(id) FROM sync_items), true);
--        SELECT setval(pg_get_serial_sequence('sync_buckets','id'),
--                      COALESCE((SELECT max(id) FROM sync_buckets), 1), true);
--        SELECT setval(pg_get_serial_sequence('mail_outbox','id'),
--                      COALESCE((SELECT max(id) FROM mail_outbox), 1), true);
--      漏了这一步 ⇒ 新插入的 id 从 1 开始撞主键。
--
-- B-5  FK 强制。PG 一律强制外键；D1 侧是否强制未在盘上证实（recon §4 R1、
--      §Q-10.6 未证实项 U-3）。**按强制口径写代码**：删 users 行前必须先删
--      sync_items / sync_buckets / refresh_tokens / devices（device-token-limits
--      与 account 两处 DELETE 的先后顺序必须由测试固定，不许靠注释约定）。
--      refresh_tokens.device_id 保持无 FK（见建表处注释）。
--
-- B-6  collation。SQLite 的比较是字节序（BINARY）。PG 若用 en_US.UTF-8 建库，
--      btree 走 strcoll，**字节不同但排序相等的两个串会被判为 UNIQUE 冲突**
--      （典型：带重音/变体字符、以及部分 ICU 排序下的全角半角）。
--      → 建库必须 LC_COLLATE 'C'（执行前置第 2 条）。
--      若已经建成别的 collation，补丁：
--        ALTER TABLE users ALTER COLUMN email TYPE text COLLATE "C";
--        -- 并对 idx_sync_user_item / idx_sync_buckets_user_device_item /
--        -- idx_devices_user_device / idx_tokens_hash 涉及的列同样处理，
--        -- 改完必须 REINDEX 或重建索引。
--
-- B-7  batch() 的事务语义不在 DDL 里，但没有它就错。D1 的 batch 是原子批，
--      PG 侧必须**同一连接** BEGIN/COMMIT，不许在连接池上逐条发
--      （recon §4 R2）。这条属于 shim 的责任，在此留痕防止只在 shim 里写注释。
--
-- B-8  run() 的 changes。D1 返回 meta.changes；PG 用 rowCount，且
--      **DDL / 无 RETURNING 的语句可能拿到 null** ⇒ 必须归一化为 0
--      （recon §4 R3）。写预算护栏依赖这个数。
--
-- B-9  时间值全部由 JS 传入，SQL 里不用 now() 参与业务。方言扫描
--      （strftime / unixepoch / datetime() / julianday）0 命中，
--      所以移植后也保持一致——**不要**顺手把 epoch ms 换成 timestamptz。
--
-- B-10 无关但容易踩：本文件用 `-1`（单事务）执行。PG 的
--      CREATE INDEX 在事务内可用；数据量大到需要 CONCURRENTLY 时不能进事务，
--      届时另写 0002+，不要改本文件。