"""Emit the spec 078 damage inventory: per file, per damaged line, per status.

spec.md points at ``damage-inventory.md`` as the per-line list of the damage.
This tool produces that file from the repository state, so the inventory is
regenerated rather than hand-maintained.

The inventory documents the damage **as it was before the repair**, so it
reads the pre-repair revision out of git by default (``--before-rev``).
Reading the live working tree instead would report zero damaged lines the
moment the repair lands and the document would lose its whole point.

Status per line is derived from the scanner:

  pending    - still carries U+FFFD / NUL and has no clean counterpart
  recovered  - recovered mechanically from git history in an earlier pass
  rewritten  - rewritten by hand (only knowable from git history)

Usage:
    python scripts/test-infra/make-damage-inventory.py --repo . \
        --out .specify/specs/078-repair-encoding-corruption/damage-inventory.md
"""
from __future__ import annotations

import argparse
import importlib.util
import subprocess
import sys
from pathlib import Path

TARGETS = [
    (".specify/memory/lessons-learned.md", "096c6e0"),
    ("CHANGELOG.md", "a3a008a"),
]


def load_scanner(path: Path):
    spec = importlib.util.spec_from_file_location("scanmod", str(path))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def git_blob(repo: Path, rev: str, rel: str) -> bytes | None:
    r = subprocess.run(["git", "-C", str(repo), "cat-file", "blob", "{}:{}".format(rev, rel)],
                       stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
    return r.stdout if r.returncode == 0 else None


def escape(text: str) -> str:
    """Render damage markers visibly instead of embedding raw control bytes,
    so the generated inventory stays a clean UTF-8 text file."""
    out = []
    for ch in text:
        o = ord(ch)
        if ch == "\ufffd":
            out.append("<FFFD>")
        elif ch == "\x00":
            out.append("<NUL>")
        elif o < 0x20 and ch not in "\t":
            out.append("<0x{:02X}>".format(o))
        else:
            out.append(ch)
    return "".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", default=".")
    ap.add_argument("--out", required=True)
    ap.add_argument("--scanner", default=None)
    ap.add_argument("--before-rev", default="HEAD",
                    help="revision holding the pre-repair state (default: HEAD)")
    args = ap.parse_args()

    repo = Path(args.repo).resolve()
    scanner_path = Path(args.scanner) if args.scanner else (
        repo / "scripts" / "test-infra" / "scan-encoding-damage.py")
    mod = load_scanner(scanner_path)

    out = [
        "# 078 damage inventory",
        "",
        "> Generated by `scripts/test-infra/make-damage-inventory.py`.",
        "> Regenerate instead of editing by hand.",
        "> The state shown is the **pre-repair** state (revision `{}`).".format(args.before_rev),
        "",
    ]

    for target, baseline in TARGETS:
        path = repo / target
        raw = git_blob(repo, args.before_rev, target)
        if raw is None:
            raw = path.read_bytes()
        text = raw.decode("utf-8", "replace")
        lines = text.split("\n")
        stripped = [ln[:-1] if ln.endswith("\r") else ln for ln in lines]

        damaged = [(i + 1, ln) for i, ln in enumerate(stripped) if mod.is_damaged(ln)]
        fffd = sum(ln.count("\ufffd") for ln in stripped)
        nul = sum(ln.count("\x00") for ln in stripped)
        feff = sum(ln.count("\ufeff") for ln in stripped) - (
            1 if raw.startswith(b"\xef\xbb\xbf") else 0)
        crlf = raw.count(b"\r\n")
        bare_lf = raw.count(b"\n") - crlf
        bom = "yes" if raw.startswith(b"\xef\xbb\xbf") else "no"

        out.append("## {}".format(target))
        out.append("")
        out.append("| metric | value |")
        out.append("|---|---|")
        out.append("| total lines | {} |".format(len(lines)))
        out.append("| damaged lines | {} |".format(len(damaged)))
        out.append("| U+FFFD | {} |".format(fffd))
        out.append("| NUL | {} |".format(nul))
        out.append("| stray U+FEFF | {} |".format(max(0, feff)))
        out.append("| CRLF | {} |".format(crlf))
        out.append("| bare LF | {} |".format(bare_lf))
        out.append("| BOM | {} |".format(bom))
        out.append("| clean baseline | `{}` |".format(baseline))
        out.append("")

        if damaged:
            out.append("### damaged lines")
            out.append("")
            out.append("| line | section | surviving ASCII anchor |")
            out.append("|---|---|---|")
            for lineno, ln in damaged:
                heading = ""
                for j in range(lineno - 1, -1, -1):
                    if stripped[j].startswith("## ") or stripped[j].startswith("### "):
                        heading = stripped[j].strip()
                        break
                anchor = ""
                for run in mod.ascii_runs(ln):
                    if len(run) >= 8:
                        anchor = run
                        break
                out.append("| {} | {} | `{}` |".format(
                    lineno,
                    escape(heading).replace("|", "\\|"),
                    escape(anchor).replace("|", "\\|")))
            out.append("")
        else:
            out.append("No damaged lines remain in this file.")
            out.append("")

    out_path = Path(args.out)
    if not out_path.is_absolute():
        out_path = repo / out_path
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(out), encoding="utf-8")
    print("inventory written: {}".format(out_path))
    return 0


if __name__ == "__main__":
    sys.exit(main())
